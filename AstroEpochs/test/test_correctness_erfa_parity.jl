@testset "ERFA parity — scale transforms" begin
    for (name, expected) in _TRANSFORMS
        f = getfield(AstroEpochs, name)
        @test [f(a, b) for (a, b) in _DATES] == expected
    end
    @test [dtdb(a, b, 0.0, 0.0, 0.0, 0.0) for (a, b) in _DATES] == _DTDB
end

@testset "ERFA parity — UTC and TAI across a leap second" begin
    for ((a, b), expected) in _UTCTAI
        @test utctai(a, b) == expected
    end
    for ((a, b), expected) in _TAIUTC
        @test taiutc(a, b) == expected
    end
end

@testset "ERFA parity — calendar" begin
    for ((y, m, d), expected) in _CAL2JD
        @test cal2jd(y, m, d) == expected
    end
    for ((a, b), expected) in _JD2CAL
        @test jd2cal(a, b) == expected
    end
end

@testset "ERFA parity — date and time of day, with leap seconds" begin
    for ((sc, a, b), expected) in _D2DTF
        @test d2dtf(sc, 3, a, b) == expected
    end
    for ((sc, y, m, d, h, mi, s), expected) in _DTF2D
        @test dtf2d(sc, y, m, d, h, mi, s) == expected
    end
    # What ERFA reports as a status, the port throws.
    @test_throws DomainError cal2jd(2023, 2, 29)
    @test_throws DomainError cal2jd(2024, 13, 1)
    @test_throws DomainError jd2cal(-1.0e5, 0.0)
    @test_throws ArgumentError dtf2d(:utc, 2024, 6, 1, 23, 59, 60.0)     # not a leap-second day
    @test_throws ArgumentError dtf2d(:tt, 2016, 12, 31, 23, 59, 60.5)    # nor is any day in TT
end

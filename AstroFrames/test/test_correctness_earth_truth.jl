@testset "Earth chains against ERFA: obliquity" begin
    # The ecliptic edges, where a 0.4 mas rounding lived until this comparison
    # found it. Tight, because there is nothing left to explain a residual.
    original = frame_theory()
    try
        set_frame_theory!(FK5())
        for case in _TRUTH
            t = Time(case.jd_utc, 0.0, :utc, :jd)       # the epoch the truth is defined at; see above
            for (ε_truth, src, dst) in ((case.mean_obliquity, MODEq(), MODEc()),
                                        (case.true_obliquity, TODEq(), TODEc()))
                R = axes_rotation(src, dst, t)[1:3, 1:3]
                ε_ours = atan(R[2, 3], R[2, 2])       # the X-rotation angle
                @test abs(rad2deg(ε_ours - ε_truth)) * 3600 * 1e6 < 0.01
            end
        end
    finally
        set_frame_theory!(original)
    end
end

@testset "the truth data still describes the EOP it was generated with" begin
    # The comparison is only meaningful while both sides use the same EOP. If
    # the table underneath us moves, the residuals move for reasons that are
    # not code changes — and this is where that shows up, rather than as a
    # mysterious failure in one of the tests above.
    for case in _TRUTH
        jd_utc = case.jd_utc
        @test eop(FK5()).Δut1_utc(jd_utc) ≈ case.eop.dut1_s atol = 1e-9
        @test eop(FK5()).x(jd_utc)        ≈ case.eop.xp_as  atol = 1e-9
        @test eop(FK5()).y(jd_utc)        ≈ case.eop.yp_as  atol = 1e-9
    end
end

"""
    _truth_angle_μas(A, B) -> Float64

Angle between two rotation matrices, in microarcseconds.

Uses the skew part rather than `acos((tr(R) − 1)/2)`: every angle compared here
is tiny, and near θ = 0 the trace formula evaluates `acos` at `1 − θ²/2`, where
machine epsilon propagates to a relative error of about `eps/θ²`.
"""
function _truth_angle_μas(A::AbstractMatrix, B::AbstractMatrix)
    R = A * transpose(B)
    v = 0.5 .* (R[3,2] - R[2,3], R[1,3] - R[3,1], R[2,1] - R[1,2])
    return rad2deg(asin(clamp(sqrt(sum(abs2, v)), -1.0, 1.0))) * 3600 * 1e6
end

# --- IAU-2006/2000A ----------------------------------------------------------
#
# The shipped default, and the chain held to the reference implementation.
# Every edge measures 0.000–0.005 µas. The bound is ten times that, which still
# catches the Earth-rotation-angle precision loss this comparison found — that
# was 0.703 µas — by a factor of fourteen.

const _TOL_IAU2006 = 0.05

# --- FK5 / IAU-76-80 ---------------------------------------------------------
#
# The legacy chain carries three residuals that are understood and deliberately
# not fixed, because closing them would mean departing from
# SatelliteToolboxTransformations for a chain nobody should be reaching for.
# Each bound sits just above the effect that explains it.

const _TOL_FK5 = (
    # Frame bias and IAU-1976 precession are bit-identical to ERFA.
    ICRF_to_MJ2000Eq  = 0.005,
    MJ2000Eq_to_MODEq = 0.005,
    # STB's `nutation_fk5` carries a 0.4 mas rounding in the mean obliquity
    # (Vallado's 23.439291° against the IERS 84381.448″). Inside the nutation
    # matrix it cancels to first order and leaves δ·Δψ, which peaks near
    # 0.034 µas when Δψ reaches its ~17″ extreme.
    MODEq_to_TODEq    = 0.10,
    # GMST-82 is AstroFrames' own, from UT1 in two parts as `eraGmst82` takes it;
    # measured 0.014 µas. Until 2026-09-30 it came from STB's single-date GMST,
    # which needed 2 µas, and the truth itself rounded UT1.
    TODEq_to_PEF      = 0.05,
    # The commutator xp·yp: STB orders the two polar-motion rotations the other
    # way from ERFA. A real difference between the approximate polar motion the
    # FK5 convention specifies and ERFA's rigorous form — not a defect. The
    # bound covers polar motion well beyond anything in the IERS record.
    PEF_to_ITRF       = 0.5,
    # The composed chain, now dominated by the polar-motion commutator.
    ICRF_to_ITRF_fk5  = 0.5,
)

@testset "Earth chains against ERFA: IAU-2006/2000A" begin
    original = frame_theory()
    try
        set_frame_theory!(IAU2006())
        for case in _TRUTH
            t = Time(case.jd_utc, 0.0, :utc, :jd)       # the epoch the truth is defined at; see above
            m = case.matrices
            for (truth, from, to) in ((m.GCRF_to_CIRS,         GCRF(), CIRS()),
                                      (m.CIRS_to_TIRS,         CIRS(), TIRS()),
                                      (m.TIRS_to_ITRF,         TIRS(), ITRF()),
                                      (m.GCRF_to_ITRF_iau2006, GCRF(), ITRF()))
                M = Matrix(axes_rotation(from, to, t)[1:3, 1:3])
                @test _truth_angle_μas(M, truth) < _TOL_IAU2006
            end
        end
    finally
        set_frame_theory!(original)
    end
end


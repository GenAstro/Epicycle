# =============================================================================
# Body-fixed axes against SPICE — external truth for the planetary family.
#
# `test_correctness_body_fixed.jl` checks rotation *periods* against published
# values, which can only see the linear rate. This sees everything: every
# periodic term, both pole polynomials, and the rate block — SPICE returns the
# full 6×6, so `Ṙ` is checked against NAIF's own derivative rather than only
# against our chain rule. A single mistyped coefficient anywhere shows up.
#
# It is an *implementation* cross-check, not an independent theory: both sides
# descend from the same IAU report. That is the right scope — transcription
# slips, sign errors and precision loss on our side are the actual risk, and
# this catches all three. The one thing it cannot catch is an error in the
# report itself.
#
# **It also detects drift.** When NAIF reissues a PCK for an erratum, our
# hard-coded constants do not move. A mismatch then says either we are stale or
# the kernel changed — information we would not otherwise have. Phobos is a
# live example: the published table and the PCK disagree because the report was
# corrected.
#
# The numbers are in this file on purpose. Generating them needs a SPICE
# toolkit and a 128 KB kernel; doing that on every run would make the test
# depend on a download that can change underneath it. The generator lives in
# internal SPICE truth tooling, not shipped, and regenerating is a deliberate act.
#
# Truth source: SPICE `sxform("J2000", "IAU_<BODY>", et)` reading
# `pck00011.tpc`.
#
# The Phobos coefficients below were checked against the published erratum
# (Archinal et al., Table 2) and agree term for term, including the secular
# `12.72192797 T²` in the prime meridian — the PCK stores it per day squared,
# and `12.72192797 / 36525² = 9.5361e-9`, which is what appears here. So these
# are the corrected values, not the ones in the original table.
# =============================================================================


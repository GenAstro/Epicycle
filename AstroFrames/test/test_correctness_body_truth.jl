"""
    _body_angle_μas(A, B) -> Float64

Angle between two rotations, in microarcseconds, from the skew part.
"""
function _body_angle_μas(A::AbstractMatrix, B::AbstractMatrix)
    R = A * transpose(B)
    v = 0.5 .* (R[3,2] - R[2,3], R[1,3] - R[3,1], R[2,1] - R[1,2])
    return rad2deg(asin(clamp(sqrt(sum(abs2, v)), -1.0, 1.0))) * 3600 * 1e6
end

# Measured agreement is 0.000 at J2000, rising to 1.7 µas by 2050. The residual
# is the prime-meridian angle: `W = W₀ + Ẇ·d` reaches 2.6 million degrees for
# Mars by 2020, where a Float64's spacing is already ~1.7 µas, so the low bits
# are gone before any trigonometry. Physically that is 28 microns on the
# Martian surface. The bound is five times the worst measurement — tight enough
# that a wrong coefficient, which would be arcseconds or worse, cannot hide.
const _TOL_BODY_μas = 10.0

# The rate block is compared relatively, because ‖Ṙ‖ spans four orders of
# magnitude between Venus and Jupiter and one absolute bound would be
# meaningless at both ends. Measured worst case is 8.5e-12.
const _TOL_BODY_RATE = 1e-10

@testset "body-fixed axes against SPICE" begin
    for body in _BODY_TRUTH
        @testset "$(body.name)" begin
            for case in body.epochs
                M = Matrix(axes_rotation(ICRF(), CelestialBodyFixed{body.naifid}(),
                                         case.jd_tdb))
                @test _body_angle_μas(M[1:3, 1:3], case.R) < _TOL_BODY_μas
                @test norm(M[4:6, 1:3] - case.Ṙ) / norm(case.Ṙ) < _TOL_BODY_RATE
            end
        end
    end
end

# --- Phobos: the user-defined path, against the same external truth ----------
#
# Epicycle ships no Phobos model. This registers one the way a user would, from
# coefficients read out of the PCK, and holds it to SPICE's own evaluation of
# the same numbers. It is the only test that validates a user-supplied
# orientation model against an external reference, and the only one covering a
# body whose expression carries periodic terms in all three angles.

"""Mars-system nutation/precession angles M1..M5 at `T` centuries, in radians."""
_phobos_angles(T) = ntuple(i -> deg2rad(_PHOBOS.angles[i][1] +
                                        _PHOBOS.angles[i][2] * T +
                                        _PHOBOS.angles[i][3] * T^2), 5)

struct _PhobosSpice <: AbstractOrientationModel end

function AstroUniverse.body_axes_rotation(::_PhobosSpice, naifid, jd_tdb)
    d = jd_tdb - 2451545.0
    T = d / 36_525
    M = _phobos_angles(T)

    # Pole and prime meridian: polynomial plus the periodic terms, exactly the
    # form a text PCK encodes.
    α = _PHOBOS.pole_ra[1] + _PHOBOS.pole_ra[2] * T +
        sum(_PHOBOS.nut_ra[i]  * sin(M[i]) for i in 1:4)
    δ = _PHOBOS.pole_dec[1] + _PHOBOS.pole_dec[2] * T +
        sum(_PHOBOS.nut_dec[i] * cos(M[i]) for i in 1:4)
    W = _PHOBOS.pm[1] + _PHOBOS.pm[2] * d + _PHOBOS.pm[3] * d^2 +
        sum(_PHOBOS.nut_pm[i]  * sin(M[i]) for i in 1:5)

    # Rates. The pole terms move slowly; the prime meridian is dominated by the
    # linear rate, and the periodic contributions are kept because they are
    # what this test exists to exercise.
    # `dM/dT` with M in radians is a pure per-century factor, because radians
    # are dimensionless — so `d(sin M)/dT = cos(M)·dM/dT` is per century, and
    # multiplying by a coefficient in degrees gives degrees per century. An
    # extra `rad2deg` here inflates the periodic terms by 57× and, for Phobos,
    # doubles the rate outright.
    dMdT = ntuple(i -> deg2rad(_PHOBOS.angles[i][2] + 2 * _PHOBOS.angles[i][3] * T), 5)
    α̇ = deg2rad(_PHOBOS.pole_ra[2] +
                sum(_PHOBOS.nut_ra[i]  * cos(M[i]) * dMdT[i] for i in 1:4)) /
        (86_400 * 36_525)
    δ̇ = deg2rad(_PHOBOS.pole_dec[2] -
                sum(_PHOBOS.nut_dec[i] * sin(M[i]) * dMdT[i] for i in 1:4)) /
        (86_400 * 36_525)
    Ẇ = deg2rad(_PHOBOS.pm[2] + 2 * _PHOBOS.pm[3] * d) / 86_400 +
        deg2rad(sum(_PHOBOS.nut_pm[i] * cos(M[i]) * dMdT[i] for i in 1:5)) /
        (86_400 * 36_525)

    return pole_axes_rotation(deg2rad(α), deg2rad(δ), deg2rad(W), α̇, δ̇, Ẇ)
end

struct PhobosFixedTruth <: AstroFrames.AbstractAxes end
AstroFrames.hub_axes(::Type{PhobosFixedTruth}) = ICRF()
AstroFrames.axes_rotation(::ICRF, ::PhobosFixedTruth, e::EpochScales) =
    body_axes_rotation(_PhobosSpice(), 401, epoch_tdb(e))

@testset "a user-defined body against SPICE" begin
    # Looser than the shipped bodies: Phobos turns 1128°/day, so its prime
    # meridian angle is three times larger than Mars's at the same epoch and
    # loses correspondingly more of its low bits. Still far below anything a
    # wrong coefficient would produce.
    for case in _PHOBOS.epochs
        M = Matrix(axes_rotation(ICRF(), PhobosFixedTruth(), case.jd_tdb))
        @test _body_angle_μas(M[1:3, 1:3], case.R) < 50.0

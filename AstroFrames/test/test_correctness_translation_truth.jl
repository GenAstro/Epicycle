# Ephemeris positions and velocities — physical checks, and regression rows.
#
# Two kinds of test live here, and they are not equally strong. Read the
# distinction before trusting either.
#
# **The physical checks are independent and can fail for a real reason.**
# `translate` is a thin wrapper on SPICE `spkpos`, so nothing that merely calls
# SPICE again can validate it. These do not:
#
#   - the Earth–Moon barycentre closes, using *our* gravitational parameters
#     against SPICE's positions. Two independent sources for one number.
#   - velocity is the time derivative of position, by finite difference.
#   - translations compose around a triangle.
#   - each planet is inside its own published orbit.
#
# **The regression rows are a cross-check against SPICE, and are circular by
# construction.** They cannot tell you a position is right. What they pin is
# everything around it, and this is the list of things that have actually gone
# wrong: the epoch conversion and the scale it assumes, which id is observer
# and which is target, the units, the frame, and — the reason they earn their
# place — the kernel underneath. The default ephemeris is a merged file *we*
# build with a script. A rebuild that drops a body or takes it from the wrong
# source produces perfectly plausible numbers, and every other test here would
# pass.
#
# The numbers are in this file on purpose. Generating them needs a SPICE
# toolkit and a 94 MB kernel; doing it on every run would make the test depend
# on a download that can change underneath it. The generator lives in
# `generate_translation_truth.jl`, internal SPICE truth tooling, and regenerating is a
# deliberate act.
#
# Truth source: SPICE `spkezr(target, et, "J2000", "NONE", observer)`.
# =============================================================================


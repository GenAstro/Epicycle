# Symbol → body, so the generated rows stay readable.
const _BODIES = (sun = sun, mercury = mercury, venus = venus, moon = moon,
                 earth = earth, mars = mars, jupiter = jupiter, saturn = saturn,
                 uranus = uranus, neptune = neptune, pluto = pluto)

const _AU = 149_597_870.7

# The same epochs the rows were generated at, including both ends of the
# merged kernel's span — the boundaries are where a clipped segment shows up.
const _TRANSLATION_EPOCHS = (2433290.0, 2451545.0, 2458849.5, 2469854.0, 2488060.0)

# --- the regression rows -----------------------------------------------------

# Both sides are the same SPICE call, so agreement should be exact. The bound
# is one part in 1e-13 rather than equality only because the literals are
# printed and reparsed, not because any difference is expected.
const _TOL_ROW = 1e-13

@testset "ephemeris rows still match SPICE" begin
    for row in _TRANSLATION_TRUTH
        observer = getproperty(_BODIES, row.observer)
        target   = getproperty(_BODIES, row.target)
        @testset "$(row.observer) → $(row.target)" begin
            for case in row.states
                truth = collect(case.state)
                state = translate_state(observer, target, case.jd_tdb)
                @test norm(state[1:3] - truth[1:3]) / norm(truth[1:3]) < _TOL_ROW
                @test norm(state[4:6] - truth[4:6]) / norm(truth[4:6]) < _TOL_ROW

                # `translate` is the position-only path and a separate SPICE
                # call, so it is pinned too rather than assumed to agree.
                @test translate(observer, target, case.jd_tdb) ≈ truth[1:3] rtol=_TOL_ROW
            end
        end
    end
end

# --- the physical checks -----------------------------------------------------

@testset "the Earth–Moon barycentre closes" begin
    # μ_E·r_E + μ_M·r_M = 0 about the barycentre. The masses are Epicycle's
    # own; the positions are DE440's. Nothing here consults SPICE for a mass or
    # Epicycle for a position, so the two sides are genuinely independent and
    # this can fail.
    #
    # The measured residual is 4.795e-10 and does not move between epochs,
    # because it is not a position error: it is the difference between our mass
    # ratio (μ_E/μ_M = 81.3005714694) and DE440's (81.3005682215), which is
    # 4.0e-8 relative and enters the barycentre through the mass fraction. The
    # bound is set just above it, so a real positional or unit error shows up
    # rather than being absorbed.
    barycentre = CelestialBody("EMB", earth.mu + moon.mu, 1.0, 0.0, 3)

    for jd in _TRANSLATION_EPOCHS
        r_earth = translate(barycentre, earth, jd)
        r_moon  = translate(barycentre, moon,  jd)

        separation = norm(r_moon - r_earth)
        residual = norm(earth.mu .* r_earth .+ moon.mu .* r_moon) /
                   ((earth.mu + moon.mu) * separation)
        @test residual < 1e-9

        # Earth sits about 4 700 km from the barycentre, well inside itself.
        @test 4_000 < norm(r_earth) < 5_000
        @test norm(r_earth) < earth.equatorial_radius
    end
end

@testset "velocity is the derivative of position" begin
    # Central difference over ±10 s. The residual is the O(h²) truncation of
    # the difference itself, not an error in the ephemeris: it measures 1.4e-6
    # for every body and epoch, independent of speed, which is what truncation
    # looks like and what a real velocity fault would not.
    #
    # This is what catches a velocity in km/day, or a sign, or a rate block
    # read out of the wrong columns.
    h_days = 10.0 / 86_400.0

    for (observer, target) in ((earth, moon), (earth, mars), (sun, jupiter),
                               (sun, earth), (earth, sun))
        for jd in _TRANSLATION_EPOCHS
            forward  = translate(observer, target, jd + h_days)
            backward = translate(observer, target, jd - h_days)
            numerical = (forward - backward) ./ (2 * h_days * 86_400.0)

            velocity = translate_state(observer, target, jd)[4:6]
            @test norm(numerical - velocity) / norm(velocity) < 1e-5
        end
    end
end

@testset "translations compose around a triangle" begin
    # Machine precision, measured at 1.1e-16. Anything larger means a leg is
    # being resolved through a different chain of segments than the direct one.
    for jd in _TRANSLATION_EPOCHS
        for (a, b, c) in ((earth, sun, mars), (earth, moon, sun),
                          (sun, jupiter, saturn), (earth, sun, pluto))
            direct  = translate(a, c, jd)
            through = translate(a, b, jd) .+ translate(b, c, jd)
            @test norm(direct - through) / norm(direct) < 1e-14
        end
    end
end

@testset "direction and the degenerate case" begin
    for jd in _TRANSLATION_EPOCHS
        # A body relative to itself is exactly zero, not nearly zero.
        @test translate(earth, earth, jd) == zeros(3)
        @test translate_state(mars, mars, jd) == zeros(6)

        # Reversing observer and target negates, exactly.
        @test translate(earth, mars, jd) == -translate(mars, earth, jd)
        @test translate_state(sun, jupiter, jd) == -translate_state(jupiter, sun, jd)
    end
end

@testset "each planet is inside its own orbit" begin
    # Published perihelion and aphelion, padded by a couple of percent — these
    # are osculating quantities and wander. The check is coarse on purpose: it
    # exists to catch a swapped NAIF id or a unit error, both of which move a
    # distance by far more than the padding.
    #
    # Neptune and Pluto genuinely overlap near Pluto's perihelion, so distance
    # alone cannot separate those two. The regression rows above do.
    bounds = ((mercury, 0.30,  0.48), (venus,   0.71,  0.74),
              (earth,   0.97,  1.03), (mars,    1.36,  1.68),
              (jupiter, 4.90,  5.50), (saturn,  8.95, 10.20),
              (uranus, 18.20, 20.15), (neptune, 29.70, 30.45),
              (pluto,  29.50, 49.50))

    for jd in _TRANSLATION_EPOCHS
        for (body, perihelion, aphelion) in bounds
            r = norm(translate(sun, body, jd)) / _AU
            @test perihelion <= r <= aphelion
        end
    end
end

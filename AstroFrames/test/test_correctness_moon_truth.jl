# The lunar frames, MOON_PA and MOON_ME.
#
# These were implemented and then never exercised — this file is the first
# thing to run them.
#
# As with the ephemeris rows, two kinds of test live here and they are not
# equally strong. `axes_rotation(ICRF(), MoonPA(), e)` calls SPICE `sxform`, so
# comparing it against `sxform` is circular.
#
# **The physical checks are independent.** The Moon's rotation is synchronous,
# which is a fact about the Moon and not about any kernel:
#
#   - Earth, seen from the Moon and expressed in principal axes, stays within
#     the libration of the +X axis. This is the strongest test in the file:
#     it uses the orientation *and* the ephemeris together, so it fails if
#     either is wrong, or if the two disagree about the epoch.
#   - the prime meridian turns once per sidereal month.
#   - ME differs from PA by a fixed rotation, whose angles are published.
#
# **The regression rows are circular**, and earn their place on one specific
# failure: a consistent but older set of lunar kernels.
#
# Mismatched kernels are not the risk. Pairing `moon_080317.tf`, which aliases
# MOON_PA to the DE421 frame, with DE440 orientation data raises loudly —
# "PCK data required ... for MOON_PA_DE421 were not found".
#
# The quiet case is `moon_pa_de421_1900-2050.bpc` *with* `moon_080317.tf`. That
# pair is internally consistent, loads without complaint, and returns a
# rotation orthonormal to 3e-16 with determinant exactly 1. It differs from
# DE440 by 0.178 arcsec — 1.5 m on the lunar surface. Every structural check
# passes, and so does the synchronous-rotation check above, at 8.777° against
# a 15° bound. Only these rows notice. Both DE421 files are commonly already
# cached, so this is a live way to be quietly wrong rather than a hypothetical.
#
# The generator is `generate_moon_truth.jl`, internal SPICE truth tooling.
#
# Truth source: SPICE `sxform("J2000", frame, et)` reading
# `moon_pa_de440_200625.bpc` with `moon_de440_250416.tf`.
# =============================================================================


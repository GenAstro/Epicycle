const _MOON_EPOCHS = (2451545.0, 2458849.5, 2469854.0)

# --- the regression rows -----------------------------------------------------

@testset "lunar frames still match SPICE" begin
    for case in _MOON_TRUTH
        @testset "jd $(case.jd_tdb)" begin
            for (axes, truth) in ((MoonPA(), case.pa), (MoonME(), case.me))
                M = Matrix(axes_rotation(ICRF(), axes, case.jd_tdb))
                @test norm(M[1:3, 1:3] - truth.R) < 1e-13
                @test norm(M[4:6, 1:3] - truth.Ṙ) / norm(truth.Ṙ) < 1e-12
            end
        end
    end
end

# --- the physical checks -----------------------------------------------------

@testset "the Moon's rotation is synchronous" begin
    # The near side faces Earth. In principal axes the +X axis is the mean
    # Earth direction, so the true direction stays within the libration in
    # longitude and latitude — measured 4.5° to 8.8° over a year, sampled
    # weekly. The bound is 15°, comfortably above the libration and far below
    # anything a wrong epoch scale, a wrong frame, or a PA/ME mix-up produces.
    #
    # This is the one test here that consults the orientation and the ephemeris
    # at once. A 1-day epoch slip moves the Moon 13° in its orbit while the
    # frame rotates with it, so a disagreement between the two shows up
    # immediately.
    angles = Float64[]
    for jd in 2458849.5:7.0:(2458849.5 + 364.0)
        earth_icrf = translate(moon, earth, jd)
        R = Matrix(axes_rotation(ICRF(), MoonPA(), jd))[1:3, 1:3]
        earth_pa = R * earth_icrf
        push!(angles, rad2deg(acos(clamp(earth_pa[1] / norm(earth_pa), -1, 1))))
    end

    @test maximum(angles) < 15.0
    # And it is genuinely librating, not pinned at zero by some identity.
    @test maximum(angles) - minimum(angles) > 1.0
end

@testset "the prime meridian turns once per sidereal month" begin
    # From the rate block: Ṙ·Rᵀ is the skew-symmetric angular velocity, whose
    # magnitude is the spin rate. The sidereal month is 27.32166 days, and the
    # instantaneous rate varies about it with the libration — measured 27.319
    # to 27.322. This checks the rate block carries a real derivative in the
    # right units, which no orthonormality check can see.
    for jd in _MOON_EPOCHS
        M = Matrix(axes_rotation(ICRF(), MoonPA(), jd))
        Ω = M[4:6, 1:3] * M[1:3, 1:3]'
        rate = norm((Ω[3, 2], Ω[1, 3], Ω[2, 1]))
        period_days = 2π / rate / 86_400
        @test abs(period_days - 27.32166) < 0.01
    end
end

@testset "ME is a fixed rotation from PA" begin
    # The mean-Earth frame is defined as a constant offset from the principal
    # axes. "Constant" is testable: the same matrix at every epoch.
    offsets = [Matrix(axes_rotation(ICRF(), MoonME(), jd))[1:3, 1:3] *
               Matrix(axes_rotation(ICRF(), MoonPA(), jd))[1:3, 1:3]'
               for jd in _MOON_EPOCHS]

    for offset in offsets[2:end]
        @test maximum(abs.(offset - offsets[1])) < 1e-12
    end

    # And it is the published rotation. Read as a rotation vector, the three
    # components are the DE440 constants in arcseconds — 67.8526, 78.6944 and
    # 0.2914 — which is what the frame kernel encodes. A wrong or missing frame
    # kernel changes these.
    D = offsets[1]
    components = rad2deg.((0.5 * (D[3,2] - D[2,3]),
                           0.5 * (D[1,3] - D[3,1]),
                           0.5 * (D[2,1] - D[1,2]))) .* 3600

    @test abs(components[1] -  0.2914) < 1e-3
    @test abs(components[2] - 78.6944) < 1e-3
    @test abs(components[3] - 67.8526) < 1e-3

    # Total offset, about 104 arcsec — roughly a kilometre on the surface.
    @test abs(norm(components) - 103.907982) < 1e-3
end

# --- structure and routing ---------------------------------------------------

@testset "lunar frames are well formed and route" begin
    for jd in _MOON_EPOCHS
        for axes in (MoonPA(), MoonME())
            M = Matrix(axes_rotation(ICRF(), axes, jd))
            R = M[1:3, 1:3]

            @test size(M) == (6, 6)
            @test norm(R' * R - I) < 1e-14
            @test isapprox(det(R), 1; atol = 1e-14)
            @test all(iszero, M[1:3, 4:6])       # block form [R 0; Ṙ R]
            @test M[4:6, 4:6] == R

            # The reverse edge is the transpose, in both blocks.
            B = Matrix(axes_rotation(axes, ICRF(), jd))
            @test norm(B[1:3, 1:3] - R') < 1e-14
            @test norm(B[4:6, 1:3] - M[4:6, 1:3]') < 1e-14

            # Round trip through the hub.
            @test norm(Matrix(B * M) - I) < 1e-13
        end

        # PA and ME are not the same frame, and both reach the Earth chain
        # through the ICRF hub rather than needing an edge of their own.
        Rpa = Matrix(axes_rotation(ICRF(), MoonPA(), jd))[1:3, 1:3]
        Rme = Matrix(axes_rotation(ICRF(), MoonME(), jd))[1:3, 1:3]
        @test norm(Rpa - Rme) > 1e-8

        for target in (MJ2000Eq(), GCRF())
            M = Matrix(axes_rotation(MoonPA(), target, jd))
            @test norm(M[1:3, 1:3]' * M[1:3, 1:3] - I) < 1e-13
        end
    end
end

